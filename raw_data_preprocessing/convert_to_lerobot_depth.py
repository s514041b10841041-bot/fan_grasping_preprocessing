"""Convert real_world_dataset_dedup.hdf5 into a local LeRobotDataset (format v3.0, lerobot 0.4.4).

Run with the `lerobot` conda env (it has h5py):
    ~/miniconda3/envs/lerobot/bin/python claude_utility/convert_to_lerobot.py

- Reads the HDF5 read-only; never pushes to the Hub.
- fps = 30; timestamps are generated by LeRobot as frame_index / fps (orig_indices timing is not used).
- The last frame of each demo is dropped (its action is zero padding).
- Also writes meta/episode_source.json: episode_index -> HDF5 demo name and orig_demo_name.
- Depth (obs/real_depth) is added as a second camera, observation.images.depth, encoded as a
  3-channel grayscale uint8 image: one dataset-wide [depth_min, depth_max] (default: 1% / 99%
  percentiles of valid pixels), near = bright, valid pixels -> 1..255, invalid (0 or NaN) -> 0.
  The parameters are written to meta/depth_info.json; deployment must encode live depth with the
  same depth_to_rgb() and the same depth_min / depth_max. --no-use-depth gives the RGB-only dataset.
"""
import argparse
import json
import os
import sys
import time

import h5py
import numpy as np
from lerobot.datasets.lerobot_dataset import LeRobotDataset

from paths import lerobot_data, raw

HERE = os.path.dirname(os.path.abspath(__file__))
H5 = raw('real_world_dataset_dedup.hdf5')          # defaults; override on the command line
OUT = lerobot_data()
REPO_ID = 'arthur/fan_grasp'
FPS = 30
TASK = 'pick up the fan by its handle'
DEPTH_KEY = 'real_depth'


# ------------------------------------------------------------------------
# depth (same encoding as convert_grasp_fan_hdf5_to_lerobot_v3_20dim_depth.py)
# ------------------------------------------------------------------------
def valid_depth_mask(d):
    """Valid depth pixels: finite and > 0. The sensor stores 0 where it measured nothing."""
    return np.isfinite(d) & (d > 0)


def compute_depth_range(d, names, frame_stride=20, max_samples_per_demo=50_000,
                        lo_pct=1.0, hi_pct=99.0, seed=0):
    """Dataset-wide depth range from the 1% / 99% percentiles of valid pixels
    (every frame_stride-th frame of every demo, randomly subsampled)."""
    rng = np.random.default_rng(seed)
    samples = []
    for n in names:
        x = d[n]['obs'][DEPTH_KEY][::frame_stride].astype(np.float32)
        v = x[valid_depth_mask(x)].ravel()
        if v.size == 0:
            continue
        if v.size > max_samples_per_demo:
            v = rng.choice(v, max_samples_per_demo, replace=False)
        samples.append(v)
    if not samples:
        raise ValueError(f"no valid pixels in {DEPTH_KEY} of any demo; check the data.")
    d_min, d_max = np.percentile(np.concatenate(samples), [lo_pct, hi_pct])
    return float(d_min), float(d_max)


def depth_to_rgb(x, d_min, d_max):
    """One depth map (H, W) or (H, W, 1) -> (H, W, 3) uint8.
    Valid pixels map linearly to 1..255 with near = bright; invalid pixels are 0.
    Deployment must use this same function with the same d_min / d_max."""
    x = np.asarray(x, dtype=np.float32)
    if x.ndim == 3 and x.shape[-1] == 1:
        x = x[..., 0]
    valid = valid_depth_mask(x)
    y = 1.0 - np.clip((x - d_min) / (d_max - d_min), 0.0, 1.0)   # near = bright
    img = np.where(valid, 1.0 + np.round(y * 254.0), 0.0).astype(np.uint8)
    return np.repeat(img[..., None], 3, axis=-1)


def build_features(demo, use_depth=True):
    """Feature spec taken from the data, so a different camera size or joint count still works.
    With use_depth, obs/real_depth is added as a second camera (3-channel uint8 image, see depth_to_rgb)."""
    h, w, c = demo['obs/real_rgb'].shape[1:]
    n_joints = demo['obs/real_joint_pos'].shape[1]
    features = {
        'observation.images.wrist': {'dtype': 'video', 'shape': (h, w, c),
                                     'names': ['height', 'width', 'channels']},
        'observation.state': {'dtype': 'float32', 'shape': (n_joints + 1,),
                              'names': [f'joint_{i}' for i in range(n_joints)] + ['gripper']},
        'action': {'dtype': 'float32', 'shape': (demo['actions'].shape[1],),
                   'names': ['dx', 'dy', 'dz', 'drx', 'dry', 'drz', 'gripper']},
    }
    if use_depth:
        dh, dw = demo['obs'][DEPTH_KEY].shape[1:3]
        features['observation.images.depth'] = {'dtype': 'image', 'shape': (dh, dw, 3),
                                                'names': ['height', 'width', 'channels']}
    return features


def demo_names(d):
    return sorted([k for k in d.keys() if k.startswith('demo_')], key=lambda s: int(s.split('_')[1]))


def main():
    global H5, OUT, FPS, TASK, REPO_ID
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--input', default=H5, help='source HDF5 (default %(default)s)')
    ap.add_argument('--out', default=OUT, help='LeRobot dataset directory to create')
    ap.add_argument('--fps', type=int, default=FPS, help='one action per camera period (default %(default)s)')
    ap.add_argument('--task', default=TASK)
    ap.add_argument('--repo-id', default=REPO_ID)
    ap.add_argument('--use-depth', action=argparse.BooleanOptionalAction, default=True,
                    help='add obs/real_depth as observation.images.depth (--no-use-depth for RGB only)')
    ap.add_argument('--depth-min', type=float, default=None,
                    help='depth lower bound, same unit as the HDF5 (default: 1%% percentile)')
    ap.add_argument('--depth-max', type=float, default=None,
                    help='depth upper bound, same unit as the HDF5 (default: 99%% percentile)')
    args = ap.parse_args()
    H5, OUT, FPS, TASK, REPO_ID = args.input, os.path.abspath(args.out), args.fps, args.task, args.repo_id
    if os.path.exists(OUT):
        sys.exit(f"{OUT} already exists; refusing to overwrite.")
    print(f"input {H5}\noutput {OUT}\nfps {FPS} | task '{TASK}' | repo_id {REPO_ID}\n")
    t0 = time.time()
    with h5py.File(H5, 'r') as f:
        d = f['data']
        names = demo_names(d)
        robot_type = str(d[names[0]].attrs['robot_name'])
        features = build_features(d[names[0]], use_depth=args.use_depth)

        depth_info = None
        if args.use_depth:
            raw_depth = d[names[0]]['obs'][DEPTH_KEY]
            print(f"{DEPTH_KEY}: shape={raw_depth.shape}, dtype={raw_depth.dtype}")
            if args.depth_min is not None and args.depth_max is not None:
                d_min, d_max = args.depth_min, args.depth_max
                print(f"depth range (given): [{d_min}, {d_max}]")
            else:
                print("computing the dataset-wide depth range (1% / 99% percentiles) ...")
                d_min, d_max = compute_depth_range(d, names)
                print(f"depth range: [{d_min:.3f}, {d_max:.3f}]")
            if d_max <= d_min:
                raise ValueError(f"bad depth range: min={d_min}, max={d_max}")
            depth_info = {
                'source_key': DEPTH_KEY,
                'source_dtype': str(raw_depth.dtype),
                'depth_min': d_min,
                'depth_max': d_max,
                'encoding': 'linear clip to [depth_min, depth_max]; near=bright; '
                            'valid pixels -> 1..255, invalid (0 or NaN) -> 0; '
                            'grayscale replicated to 3 channels',
            }

        print("features: " + ", ".join(f"{k} {tuple(v['shape'])}" for k, v in features.items()))
        ds = LeRobotDataset.create(repo_id=REPO_ID, fps=FPS, features=features, root=OUT,
                                   robot_type=robot_type, use_videos=True, image_writer_threads=4)
        source = []
        for ep, n in enumerate(names):
            g = d[n]
            rgb = g['obs/real_rgb'][:]                                   # one demo at a time
            state = np.concatenate([g['obs/real_joint_pos'][:], g['obs/gripper_cmd'][:][:, None]], axis=1).astype(np.float32)
            act = g['actions'][:].astype(np.float32)
            L = len(act)
            assert rgb.shape[0] == L and rgb.dtype == np.uint8 and state.shape[0] == L
            assert not np.abs(act[-1, :6]).any(), (n, 'last action row is not zero padding')
            if args.use_depth:
                depth = g['obs'][DEPTH_KEY][:]
                assert depth.shape[0] == L, (n, f'depth frames {depth.shape[0]} != action frames {L}')
            for t in range(L - 1):                                       # drop the last (padding) frame
                frame = {'observation.images.wrist': rgb[t], 'observation.state': state[t],
                         'action': act[t], 'task': TASK}
                if args.use_depth:
                    frame['observation.images.depth'] = depth_to_rgb(depth[t], d_min, d_max)
                ds.add_frame(frame)
            ds.save_episode()
            source.append({'episode_index': ep, 'hdf5_demo': n, 'orig_demo_name': str(g.attrs['orig_demo_name']),
                           'num_frames': L - 1})
            del rgb
            if args.use_depth:
                del depth
            if (ep + 1) % 10 == 0 or ep + 1 == len(names):
                print(f"{ep + 1}/{len(names)} demos done  [{time.time() - t0:.0f}s]", flush=True)
        ds.finalize()
    with open(os.path.join(OUT, 'meta', 'episode_source.json'), 'w') as fp:
        json.dump(source, fp, indent=1)
    if depth_info is not None:
        with open(os.path.join(OUT, 'meta', 'depth_info.json'), 'w') as fp:
            json.dump(depth_info, fp, indent=2)
        print(f"depth parameters -> {os.path.join(OUT, 'meta', 'depth_info.json')}")
    print(f"DONE in {time.time() - t0:.0f}s -> {OUT}")


if __name__ == '__main__':
    main()
